#!/usr/bin/env ruby
# Keep artists' source files intact; generate one deferred script before Jekyll.
require 'json'

root = File.expand_path('..', __dir__)
manifest = JSON.parse(File.read(File.join(root, 'assets/gallery/manifest.json'), encoding: 'utf-8'))
slugs = manifest.fetch('pieces')
abort 'Gallery manifest must contain a nonempty array of unique slugs' unless
  slugs.is_a?(Array) && !slugs.empty? && slugs.uniq == slugs &&
  slugs.all? { |slug| slug.is_a?(String) && slug.match?(/\A[a-z0-9]+(?:-[a-z0-9]+)*\z/) }

files = Dir[File.join(root, 'assets/gallery/pieces/*.js')].sort_by do |path|
  name = File.basename(path)
  abort "Invalid gallery filename: #{name}" unless name.match?(/\A\d+-[a-z0-9]+(?:-[a-z0-9]+)*\.js\z/)
  name.to_i
end
accessions = files.map { |path| File.basename(path).to_i }
abort 'Gallery accession numbers must be unique' unless accessions.uniq == accessions
file_slugs = files.map { |path| File.basename(path, '.js').sub(/^\d+-/, '') }
abort 'Gallery manifest must match piece filenames in accession order' unless file_slugs == slugs

sources = [File.join(root, 'assets/js/gallery.js')] + files
bundle = "// Generated by scripts/gallery_bundle.rb; edit the sources, never this file.\n"
sources.each do |path|
  relative = path.delete_prefix(root + '/')
  bundle << "\n// Source: #{relative}\n"
  bundle << File.read(path, encoding: 'utf-8')
  # Separate scripts even when a source ends in a line comment or omits a semicolon.
  bundle << "\n;\n"
end
output = File.join(root, 'assets/js/gallery-bundle.js')
File.binwrite(output, bundle)
puts "gallery-bundle.js: #{bundle.bytesize} bytes, #{slugs.length} pieces"
